# Standard library
import uuid

# Third-party
from sqlalchemy import Boolean, ForeignKey, Real, Text, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import Base, IdentificationL18nMixin, CreatorMixin, TimestampMixin


class ProfileCatAchievement(
    TimestampMixin, CreatorMixin, IdentificationL18nMixin, Base
):
    __tablename__ = "profile_cat_achievement"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        description=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    name: Mapped[str] = mapped_column(
        Text,
        unique=True,
        nullable=False,
        description=(
            "Unique display name of the"
            " achievement in English (e.g."
            " 'Peak Bagger', 'Century Hiker')."
            " Overrides the mixin name to"
            " enforce NOT NULL and UNIQUE."
        ),
    )
    point_factor: Mapped[float] = mapped_column(
        Real,
        nullable=False,
        description=(
            "Numeric multiplier applied when calculating gamification points "
            "awarded for earning this achievement. Combined with rarity and "
            "category factors to determine final point value."
        ),
    )
    criteria = mapped_column(
        JSONB,
        nullable=True,
        description=(
            "JSONB object defining the machine-readable criteria that must be "
            "met to earn this achievement (e.g. distance thresholds, "
            "elevation targets, activity counts, specific POIs to visit). "
            "Evaluated by the achievement engine against user statistics and "
            "activity data."
        ),
    )
    is_active: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        server_default="true",
        description=(
            "Whether this achievement is currently active and can be earned "
            "by users. Inactive achievements are hidden from discovery but "
            "retained for users who already earned them."
        ),
    )
    is_repeatable: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        server_default="false",
        description=(
            "Whether this achievement can be earned multiple times by the "
            "same user. When false, the partial unique index on "
            "user_achievement prevents duplicate awards."
        ),
    )
    rarity_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_rarity.id"),
        nullable=False,
        description=(
            "Foreign key to core_ref_rarity defining how rare this "
            "achievement is (e.g. common, rare, legendary). Affects display "
            "styling and point factor calculations."
        ),
    )
    category_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_achievement_category.id"),
        nullable=False,
        description=(
            "Foreign key to core_ref_achievement_category classifying this "
            "achievement into a thematic group (e.g. distance, elevation, "
            "exploration, social)."
        ),
    )
    criteria_scope_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_achievement_scope.id"),
        nullable=False,
        description=(
            "Foreign key to core_ref_achievement_scope defining the temporal "
            "or spatial scope over which the criteria are evaluated (e.g. "
            "single activity, lifetime, per region)."
        ),
    )
    criteria_type_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_achievement_type.id"),
        nullable=False,
        description=(
            "Foreign key to core_ref_achievement_type classifying the kind of "
            "criteria used (e.g. cumulative, threshold, streak, collection), "
            "which determines how the achievement engine evaluates progress."
        ),
    )
