# Standard library
import uuid
from datetime import datetime

# Third-party
from sqlalchemy import DateTime, ForeignKey, Text, UniqueConstraint, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import Base, TimestampMixin, UserScopedMixin


class ProfileM2mUserCard(TimestampMixin, UserScopedMixin, Base):
    __tablename__ = "profile_m2m_user_card"
    __table_args__ = (UniqueConstraint("user_id", "card_id"),)

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        description=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    card_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("compendium_cat_card.id", ondelete="CASCADE"),
        nullable=False,
        description=(
            "Foreign key to compendium_cat_card identifying the collectible "
            "card the user has obtained. Unique per user (each card can only "
            "be collected once). Cascades on delete."
        ),
    )
    collected_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        description=(
            "Timezone-aware timestamp of when the user collected this card, "
            "typically upon visiting the associated POI or completing a "
            "related activity."
        ),
    )
    comment: Mapped[str | None] = mapped_column(
        Text,
        description=(
            "Optional free-text comment or personal note the user can attach "
            "to their collected card."
        ),
    )
    track_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("explorer_agg_track.id", ondelete="SET NULL"),
        description=(
            "Optional foreign key to explorer_agg_track linking this card "
            "collection to the recorded track during which the card was "
            "obtained. Set to NULL if the referenced track is deleted."
        ),
    )
