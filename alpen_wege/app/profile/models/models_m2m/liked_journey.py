# Standard library
import uuid

# Third-party
from sqlalchemy import ForeignKey, UniqueConstraint, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import Base, CreatedMixin, UserScopedMixin


class ProfileM2mLikedJourney(CreatedMixin, UserScopedMixin, Base):
    __tablename__ = "profile_m2m_liked_journey"
    __table_args__ = (UniqueConstraint("user_id", "journey_id"),)

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        description=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    journey_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("explorer_agg_journey.id", ondelete="CASCADE"),
        nullable=False,
        description=(
            "Foreign key to explorer_agg_journey identifying the multi-day "
            "journey the user has liked or bookmarked. Unique per user (a "
            "user can only like a journey once). Cascades on delete so the "
            "like is removed when the journey is deleted."
        ),
    )
