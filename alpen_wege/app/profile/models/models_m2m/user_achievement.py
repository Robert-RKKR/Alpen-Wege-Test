# Standard library
import uuid
from datetime import datetime

# Third-party
from sqlalchemy import Boolean, DateTime, ForeignKey, Index, Text, func, text
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import Base, TimestampMixin, UserScopedMixin


class ProfileM2mUserAchievement(TimestampMixin, UserScopedMixin, Base):
    __tablename__ = "profile_m2m_user_achievement"
    __table_args__ = (
        Index(
            "ix_profile_m2m_user_achievement_unique_first",
            "user_id",
            "achievement_id",
            unique=True,
            postgresql_where=text("NOT is_repeat"),
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        description=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    achievement_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("profile_cat_achievement.id"),
        nullable=False,
        description=(
            "Foreign key to profile_cat_achievement identifying which "
            "achievement the user earned."
        ),
    )
    collected_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        description=(
            "Timezone-aware timestamp of when the user earned this "
            "achievement, which may differ from created_at if the award was "
            "applied retroactively."
        ),
    )
    comment: Mapped[str | None] = mapped_column(
        Text,
        description=(
            "Optional free-text comment or note the user can attach when the "
            "achievement is earned (e.g. personal reflection, celebration "
            "message)."
        ),
    )
    is_repeat: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        server_default="false",
        description=(
            "Whether this record represents a repeat earn of a repeatable "
            "achievement. When false, the partial unique index ensures only "
            "one record per (user_id, achievement_id) pair."
        ),
    )
    track_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("explorer_agg_track.id", ondelete="SET NULL"),
        description=(
            "Optional foreign key to explorer_agg_track linking the "
            "achievement to the specific recorded track that triggered it. "
            "Set to NULL if the referenced track is deleted."
        ),
    )
    trip_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("explorer_agg_trip.id", ondelete="SET NULL"),
        description=(
            "Optional foreign key to explorer_agg_trip linking the "
            "achievement to the multi-day trip that triggered it. Set to NULL "
            "if the referenced trip is deleted."
        ),
    )
