# Standard library
import uuid
from datetime import datetime

# Third-party
from sqlalchemy import CheckConstraint, DateTime, ForeignKey, Text, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import Base, TimestampMixin, UserScopedMixin


class ProfileSubSchedule(TimestampMixin, UserScopedMixin, Base):
    __tablename__ = "profile_sub_schedule"
    __table_args__ = (
        CheckConstraint(
            "route_id IS NOT NULL OR journey_id IS NOT NULL",
            name="ck_profile_sub_schedule_entity",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    route_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("explorer_agg_route.id", ondelete="SET NULL"),
        comment=(
            "Optional foreign key to explorer_agg_route identifying the "
            "planned route. At least one of route_id or journey_id must be "
            "set (enforced by CHECK constraint). Set to NULL if the "
            "referenced route is deleted."
        ),
    )
    journey_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("explorer_agg_journey.id", ondelete="SET NULL"),
        comment=(
            "Optional foreign key to explorer_agg_journey identifying the "
            "planned multi-day journey. At least one of route_id or "
            "journey_id must be set (enforced by CHECK constraint). Set to "
            "NULL if the referenced journey is deleted."
        ),
    )
    track_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("explorer_agg_track.id", ondelete="SET NULL"),
        comment=(
            "Optional foreign key to explorer_agg_track linking this schedule "
            "entry to the actual recorded track once the planned activity has "
            "been completed. Set to NULL if the referenced track is deleted."
        ),
    )
    trip_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("explorer_agg_trip.id", ondelete="SET NULL"),
        comment=(
            "Optional foreign key to explorer_agg_trip linking this schedule "
            "entry to a multi-day trip that encompasses the planned activity. "
            "Set to NULL if the referenced trip is deleted."
        ),
    )
    planned_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        comment=(
            "Timezone-aware timestamp indicating when the user plans to start "
            "the scheduled route or journey."
        ),
    )
    completed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        comment=(
            "Timezone-aware timestamp indicating when the scheduled activity "
            "was actually completed. NULL if the activity has not yet been "
            "completed or was skipped."
        ),
    )
    status_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_schedule_status.id"),
        nullable=False,
        comment=(
            "Foreign key to core_ref_schedule_status indicating the current "
            "status of this scheduled activity (e.g. planned, in_progress, "
            "completed, skipped, cancelled)."
        ),
    )
    notes: Mapped[str | None] = mapped_column(
        Text,
        comment=(
            "Free-text notes the user can attach to this schedule entry, such "
            "as preparation reminders, gear to bring, or meeting point "
            "details."
        ),
    )
