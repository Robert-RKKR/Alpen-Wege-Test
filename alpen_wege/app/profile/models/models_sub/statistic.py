# Standard library
import uuid

# Third-party
from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    ForeignKey,
    Integer,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import Base, TimestampMixin, UserScopedMixin


class ProfileSubStatistic(TimestampMixin, UserScopedMixin, Base):
    __tablename__ = "profile_sub_statistic"
    __table_args__ = (
        UniqueConstraint(
            "user_id",
            "sport_type_id",
            "scope",
            "scope_year",
            "scope_month",
            name="uq_profile_sub_statistic_bucket",
            postgresql_nulls_not_distinct=True,
        ),
        CheckConstraint(
            "scope IN ('all', 'year', 'month')",
            name="ck_profile_sub_statistic_scope",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    scope: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        comment=(
            "Time scope for aggregation: 'all' (lifetime), 'year' (calendar "
            "year), 'month' (calendar month)."
        ),
    )
    scope_year: Mapped[int | None] = mapped_column(
        Integer,
        comment=(
            "Calendar year (UTC) for year and month scoped statistics. "
            "NULL for scope 'all'."
        ),
    )
    scope_month: Mapped[int | None] = mapped_column(
        Integer,
        comment=(
            "Calendar month 1-12 (UTC) for month scoped statistics. "
            "NULL for scope 'all' and 'year'."
        ),
    )
    sport_type_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("core_ref_sport_type.id", ondelete="CASCADE"),
        comment=(
            "FK to core_ref_sport_type. NULL means all-sports aggregate. "
            "CASCADE on sport type delete."
        ),
    )
    total_distance_m: Mapped[int] = mapped_column(
        BigInteger,
        nullable=False,
        server_default="0",
        comment=(
            "Cumulative distance in meters across all activities within the "
            "given scope."
        ),
    )
    total_distance_graph = mapped_column(
        JSONB,
        nullable=True,
        comment=(
            "JSONB object storing time-series data of distance accumulation "
            "over the scope period, used to render distance trend charts in "
            "the user"
        ),
    )
    total_elevation_m: Mapped[int] = mapped_column(
        BigInteger,
        nullable=False,
        server_default="0",
        comment=(
            "Cumulative elevation gain in meters across all activities within "
            "the given scope."
        ),
    )
    total_elevation_graph = mapped_column(
        JSONB,
        nullable=True,
        comment=(
            "JSONB object storing time-series data of elevation gain "
            "accumulation over the scope period, used to render elevation "
            "trend charts in the user"
        ),
    )
    total_activities: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        server_default="0",
        comment=(
            "Total number of completed activities (recorded tracks) within "
            "the given scope."
        ),
    )
    total_activities_graph = mapped_column(
        JSONB,
        nullable=True,
        comment=(
            "JSONB object storing time-series data of activity counts over "
            "the scope period, used to render activity frequency charts in "
            "the user"
        ),
    )
    total_time_s: Mapped[int] = mapped_column(
        BigInteger,
        nullable=False,
        server_default="0",
        comment=(
            "Cumulative time spent on activities in seconds within the given "
            "scope."
        ),
    )
    total_time_graph = mapped_column(
        JSONB,
        nullable=True,
        comment=(
            "JSONB object storing time-series data of time spent on "
            "activities over the scope period, used to render duration trend "
            "charts in the user"
        ),
    )
    total_moving_time_s: Mapped[int] = mapped_column(
        BigInteger,
        nullable=False,
        server_default="0",
        comment="Cumulative moving time in seconds, excluding stops.",
    )
    total_elevation_loss_m: Mapped[int] = mapped_column(
        BigInteger,
        nullable=False,
        server_default="0",
        comment="Cumulative elevation loss in meters.",
    )
    total_plans_created: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        server_default="0",
        comment=(
            "Total number of schedule entries (planned activities) created by "
            "the user within the given scope."
        ),
    )
    total_plans_completed: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        server_default="0",
        comment=(
            "Total number of scheduled activities that the user completed "
            "within the given scope."
        ),
    )
    total_plans_skipped: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        server_default="0",
        comment=(
            "Total number of scheduled activities that the user skipped or "
            "cancelled within the given scope."
        ),
    )
    current_streak_days: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        server_default="0",
        comment=(
            "Number of consecutive days with at least one recorded activity, "
            "counting back from the most recent active day."
        ),
    )
    longest_streak_days: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        server_default="0",
        comment=(
            "Longest consecutive-day activity streak ever achieved by the "
            "user within the given scope."
        ),
    )
    total_points: Mapped[int] = mapped_column(
        BigInteger,
        nullable=False,
        server_default="0",
        comment=(
            "Cumulative gamification points earned by the user within the "
            "given scope."
        ),
    )
    unique_pois_count: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        server_default="0",
        comment=(
            "Number of distinct POIs the user has visited within the given "
            "scope, from the visit log."
        ),
    )
    unique_regions_count: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        server_default="0",
        comment=(
            "Number of distinct geographic regions the user has been active "
            "in within the given scope."
        ),
    )
    active_days: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        server_default="0",
        comment="Number of distinct days (UTC) with at least one activity.",
    )
    max_elevation_m: Mapped[int | None] = mapped_column(
        Integer,
        comment="Highest elevation reached across all tracks in this scope.",
    )
    longest_track_m: Mapped[int | None] = mapped_column(
        Integer,
        comment="Distance in meters of the longest single track in this scope.",
    )
    longest_track_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("explorer_agg_track.id", ondelete="SET NULL"),
        comment="FK to the longest track. SET NULL on track delete.",
    )
