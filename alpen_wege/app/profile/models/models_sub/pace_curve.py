# Standard library
import uuid

# Third-party
from sqlalchemy import ForeignKey, Integer, REAL, UniqueConstraint, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import Base, TimestampMixin, UserScopedMixin


class ProfileSubPaceCurve(TimestampMixin, UserScopedMixin, Base):
    __tablename__ = "profile_sub_pace_curve"
    __table_args__ = (
        UniqueConstraint("user_id", "sport_type_id", "gradient_bin"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    sport_type_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_sport_type.id"),
        nullable=False,
        comment=(
            "Foreign key to core_ref_sport_type identifying the sport (e.g. "
            "hiking, trail running, cycling) this pace data point belongs to."
        ),
    )
    gradient_bin: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        comment=(
            "Gradient bucket in percent (e.g. -10, 0, 5, 15). Each unique "
            "(user_id, sport_type_id, gradient_bin) triple defines one pace "
            "data point on the user"
        ),
    )
    speed_kmh: Mapped[float] = mapped_column(
        REAL,
        nullable=False,
        comment="User",
    )
    sample_points: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        comment=(
            "Number of GPS track data points that contributed to the "
            "speed_kmh average for this gradient bin, indicating the "
            "statistical confidence of the pace estimate."
        ),
    )
