# Standard library
import uuid

# Third-party
from sqlalchemy import (
    CheckConstraint,
    ForeignKey,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

# Local application
from app.core.base import Base, TimestampMixin


class ProfileAccessPolicy(TimestampMixin, Base):
    __tablename__ = "profile_access_policy"
    __table_args__ = (
        CheckConstraint(
            "user_group IN ('administrator', 'viewer', 'guest', 'editor')",
            name="ck_profile_access_policy_user_group",
        ),
        CheckConstraint(
            "action IN ('create', 'read', 'update', 'delete')",
            name="ck_profile_access_policy_action",
        ),
        CheckConstraint(
            "scope IN ('own', 'public', 'all')",
            name="ck_profile_access_policy_scope",
        ),
        UniqueConstraint(
            "user_group",
            "resource_type_id",
            "action",
            name="uq_profile_access_policy_group_resource_action",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by the database. Uniquely "
            "identifies a single access policy row."
        ),
    )
    user_group: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        comment=(
            "Authorization group this policy applies to. "
            "Must be one of 'administrator', 'editor', 'viewer', or 'guest'."
        ),
    )
    resource_type_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_resource_type.id", ondelete="CASCADE"),
        nullable=False,
        comment=(
            "FK to core_ref_resource_type. The resource type this policy "
            "governs."
        ),
    )
    action: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        comment=(
            "The CRUD action this policy permits. "
            "Must be one of 'create', 'read', 'update', or 'delete'."
        ),
    )
    scope: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        comment=(
            "Visibility/ownership scope for the action. "
            "'own' = only creator's rows, "
            "'public' = own + is_public rows, "
            "'all' = unrestricted."
        ),
    )

    resource_type = relationship("CoreRefResourceType", lazy="joined")
