# Standard library
import uuid

# Third-party
from sqlalchemy import CheckConstraint, ForeignKey, UniqueConstraint, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import Base, CreatedMixin


class SocialM2mFollow(CreatedMixin, Base):
    __tablename__ = "social_m2m_follow"
    __table_args__ = (
        UniqueConstraint("follower_id", "following_id"),
        CheckConstraint(
            "follower_id <> following_id",
            name="ck_social_m2m_follow_no_self",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid(). Uniquely identifies each follow relationship."
        ),
    )
    follower_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("profile_usr_user.id", ondelete="CASCADE"),
        nullable=False,
        comment=(
            "UUID of the user who is following another user. References "
            "profile_usr_user.id with CASCADE delete so the follow is removed "
            "when the follower account is deleted."
        ),
    )
    following_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("profile_usr_user.id", ondelete="CASCADE"),
        nullable=False,
        comment=(
            "UUID of the user being followed. References profile_usr_user.id "
            "with CASCADE delete so the follow is removed when the followed "
            "account is deleted."
        ),
    )
