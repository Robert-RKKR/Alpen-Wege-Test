# Standard library
import uuid

# Third-party
from sqlalchemy import CheckConstraint, ForeignKey, Text, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import Base, TimestampMixin, UserScopedMixin


class SocialSubComment(TimestampMixin, UserScopedMixin, Base):
    __tablename__ = "social_sub_comment"
    __table_args__ = (
        CheckConstraint(
            "entity_type IN ( "
            "'route', 'journey', 'segment', "
            "'track', 'trip', 'post')",
            name="ck_social_sub_comment_entity_type",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        description=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid(). Uniquely identifies each comment."
        ),
    )
    entity_type: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        description=(
            "Polymorphic discriminator indicating the type of entity this "
            "comment is attached to. Must be one of , , , , , or ."
        ),
    )
    entity_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        nullable=False,
        description=(
            "UUID of the entity (route, journey, segment, track, trip, or "
            "post) that this comment belongs to. Used together with "
            "entity_type for polymorphic lookup."
        ),
    )
    comment: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        description="The full text body of the user",
    )
    parent_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("social_sub_comment.id", ondelete="CASCADE"),
        description="Optional self-referencing foreign key to another comment",
    )
