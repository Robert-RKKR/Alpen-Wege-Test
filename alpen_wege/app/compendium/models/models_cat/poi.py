# Standard library
import uuid

# Third-party
from geoalchemy2 import Geometry
from sqlalchemy import ForeignKey, Integer, Text, func
from sqlalchemy.orm import Mapped, mapped_column, relationship

# Local application
from app.core.base import (
    Base,
    IdentificationL18nMixin,
    CreatorMixin,
    TimestampMixin,
)


class CompendiumCatPoi(TimestampMixin, CreatorMixin, IdentificationL18nMixin, Base):
    __tablename__ = "compendium_cat_poi"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by "
            "the database using gen_random_uuid()."
        ),
    )
    name: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        unique=True,
        comment=(
            "Canonical English name of the POI, "
            "unique across all records (e.g. "
            "'Zugspitze', 'Berliner Huette')."
        ),
    )
    location = mapped_column(
        Geometry("POINT", srid=4326),
        nullable=False,
        comment=(
            "Geographic coordinates of the POI as a "
            "PostGIS Point in WGS 84 (SRID 4326), "
            "used for map placement and proximity "
            "searches."
        ),
    )
    altitude_m: Mapped[int | None] = mapped_column(
        Integer,
        comment=(
            "Elevation of the POI in metres above "
            "sea level (e.g. 3798 for "
            "Grossglockner). NULL when unknown."
        ),
    )
    data_source_url: Mapped[str | None] = mapped_column(
        Text,
        comment=(
            "URL of the external data source used "
            "to populate this POI record (e.g. "
            "Wikipedia, OpenStreetMap)."
        ),
    )
    compendium_type_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_compendium_type.id"),
        nullable=False,
        comment=(
            "FK to core_ref_compendium_type. The POI "
            "category (e.g. peak, hut, pass, lake)."
        ),
    )
    poi_access_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("compendium_sub_poi_access.id"),
        comment=(
            "Optional FK to the access information "
            "for this POI (parking, transport, "
            "water, toilets)."
        ),
    )
    main_photo_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("asset_agg_photo.id"),
        comment=(
            "Optional FK to the primary photo "
            "representing this POI in listings and "
            "detail views."
        ),
    )
    main_region_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("compendium_cat_region.id"),
        nullable=False,
        comment=(
            "FK to the primary geographic region "
            "this POI belongs to (e.g. the mountain "
            "range or valley)."
        ),
    )

    compendium_type = relationship("CoreRefCompendiumType", foreign_keys=[compendium_type_id], lazy="raise")
    main_region = relationship("CompendiumCatRegion", foreign_keys=[main_region_id], lazy="raise")
