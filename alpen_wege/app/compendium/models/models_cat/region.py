# Standard library
import uuid

# Third-party
from geoalchemy2 import Geometry
from sqlalchemy import ForeignKey, Text, func
from sqlalchemy.orm import Mapped, mapped_column, relationship

# Local application
from app.core.base import (
    Base,
    IdentificationL18nMixin,
    CreatorMixin,
    TimestampMixin,
)


class CompendiumCatRegion(TimestampMixin, CreatorMixin, IdentificationL18nMixin, Base):
    __tablename__ = "compendium_cat_region"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by "
            "the database using gen_random_uuid()."
        ),
    )
    name: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        unique=True,
        comment=(
            "Canonical English name of the region, "
            "unique across all records (e.g. "
            "'Zillertal Alps', 'Stubai Valley')."
        ),
    )
    location = mapped_column(
        Geometry("POINT", srid=4326),
        nullable=False,
        comment=(
            "Representative centroid of the region "
            "as a PostGIS Point in WGS 84 "
            "(SRID 4326), used for map placement."
        ),
    )
    country_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("compendium_cat_country.id"),
        nullable=False,
        comment=(
            "FK to compendium_cat_country. The country this region belongs to."
        ),
    )
    region_type_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_region_type.id"),
        nullable=False,
        comment=(
            "FK to core_ref_region_type. The region "
            "classification (e.g. mountain range, "
            "valley, national park)."
        ),
    )
    iso_code: Mapped[str | None] = mapped_column(
        Text,
        comment=(
            "Optional ISO 3166-2 subdivision code "
            "for administrative regions (e.g. "
            "'AT-7' for Tyrol). NULL for "
            "non-administrative areas."
        ),
    )
    parent_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("compendium_cat_region.id"),
        comment=(
            "Self-referential FK to a parent region, "
            "enabling hierarchical nesting. NULL "
            "for top-level regions."
        ),
    )
    bbox = mapped_column(
        Geometry("POLYGON", srid=4326),
        nullable=True,
        comment=(
            "Bounding-box polygon in WGS 84 "
            "(SRID 4326) defining the geographic "
            "extent, used for spatial containment "
            "queries and map viewport fitting."
        ),
    )
    icon_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("asset_agg_icon.id", ondelete="RESTRICT"),
        index=True,
        comment=(
            "FK to asset_agg_icon with RESTRICT delete. The flag or coat of "
            "arms of the region (an SVG). NULL until one is linked."
        ),
    )

    country = relationship("CompendiumCatCountry", foreign_keys=[country_id], lazy="raise")
    region_type = relationship("CoreRefRegionType", foreign_keys=[region_type_id], lazy="raise")
    parent = relationship("CompendiumCatRegion", foreign_keys=[parent_id], remote_side="CompendiumCatRegion.id", lazy="raise")
