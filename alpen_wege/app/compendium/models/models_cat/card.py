# Standard library
import uuid
from datetime import datetime

# Third-party
from sqlalchemy import CHAR, CheckConstraint, DateTime, ForeignKey, Identity, Integer, SmallInteger, String, Text, UniqueConstraint, func
from sqlalchemy.orm import Mapped, mapped_column, relationship

# Local application
from app.core.base import Base, IdentificationL18nMixin, CreatorMixin, TimestampMixin

RENDER_STATUSES = ("pending", "rendering", "done", "failed")


class CompendiumCatCard(TimestampMixin, CreatorMixin, IdentificationL18nMixin, Base):
    __tablename__ = "compendium_cat_card"
    __table_args__ = (
        UniqueConstraint("card_number", name="uq_compendium_cat_card_number"),
        CheckConstraint("card_number > 0", name="ck_compendium_cat_card_number_positive"),
        CheckConstraint(
            "render_status IN ('pending', 'rendering', 'done', 'failed')",
            name="ck_compendium_cat_card_render_status",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    card_number: Mapped[int] = mapped_column(
        Integer,
        Identity(always=False),
        nullable=False,
        comment=(
            "Unique order number of the card, printed on it as No 013. Assigned from an identity sequence; "
            "may be set explicitly (create, update, CSV) to keep the number of a card printed earlier."
        ),
    )
    name: Mapped[str | None] = mapped_column(
        Text,
        comment=(
            "Optional display name for the collectible card in English. May "
            "be NULL when the card inherits its name from the linked POI."
        ),
    )
    rarity_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("core_ref_rarity.id"),
        comment=(
            "Optional foreign key to the rarity tier of this card (e.g. "
            "common, rare, legendary). References core_ref_rarity.id."
        ),
    )
    compendium_type_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("core_ref_compendium_type.id"),
        comment=(
            "Optional foreign key to the compendium type this card represents "
            "(e.g. peak, hut, pass). References core_ref_compendium_type.id."
        ),
    )
    poi_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("compendium_cat_poi.id"),
        nullable=False,
        index=True,
        comment=(
            "FK to compendium_cat_poi. The point of interest this card is "
            "tied to. Required (NOT NULL)."
        ),
    )
    main_photo_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("asset_agg_photo.id"),
        comment=(
            "Optional foreign key to the primary photo used as the card "
            "artwork or thumbnail. References asset_agg_photo.id."
        ),
    )
    difficulty_level_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("core_ref_difficulty_level.id"),
        comment=(
            "FK to core_ref_difficulty_level. Optional general difficulty of reaching this place. "
            "NULL (and no difficulty_sport_id) hides the difficulty on the card."
        ),
    )
    difficulty_sport_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("core_ref_difficulty_sport.id"),
        comment=(
            "FK to core_ref_difficulty_sport. Optional sport-specific grade (e.g. SAC T3). "
            "Shown on the card instead of difficulty_level_id when both are set."
        ),
    )
    render_status: Mapped[str | None] = mapped_column(
        String(16),
        comment="State of the generated card files: pending, rendering, done or failed. NULL when never rendered.",
    )
    render_version: Mapped[int | None] = mapped_column(
        SmallInteger,
        comment="Template version the stored files were rendered with. A newer template version makes the files stale.",
    )
    render_hash: Mapped[str | None] = mapped_column(
        CHAR(64),
        comment="SHA-256 of the render models (all languages) the stored files were made from. Files are stale when it no longer matches.",
    )
    rendered_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        comment="When the stored card files were rendered.",
    )

    rarity = relationship("CoreRefRarity", foreign_keys=[rarity_id], lazy="raise")
    compendium_type = relationship("CoreRefCompendiumType", foreign_keys=[compendium_type_id], lazy="raise")
    poi = relationship("CompendiumCatPoi", foreign_keys=[poi_id], lazy="raise")
    main_photo = relationship("AssetAggPhoto", foreign_keys=[main_photo_id], lazy="raise", viewonly=True)
    difficulty_level = relationship("CoreRefDifficultyLevel", foreign_keys=[difficulty_level_id], lazy="raise", viewonly=True)
    difficulty_sport = relationship("CoreRefDifficultySport", foreign_keys=[difficulty_sport_id], lazy="raise", viewonly=True)
