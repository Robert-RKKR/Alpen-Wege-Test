# Standard library
import uuid

# Third-party
from geoalchemy2 import Geometry
from sqlalchemy import ARRAY, ForeignKey, Text, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import (
    Base,
    IdentificationL18nMixin,
    CreatorMixin,
    TimestampMixin,
)


class CompendiumCatCountry(TimestampMixin, CreatorMixin, IdentificationL18nMixin, Base):
    __tablename__ = "compendium_cat_country"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by "
            "the database using gen_random_uuid()."
        ),
    )
    name: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        unique=True,
        comment=(
            "Canonical English name of the country, "
            "unique across all country records "
            "(e.g. 'Austria', 'Switzerland')."
        ),
    )
    iso_code: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        unique=True,
        comment=(
            "ISO 3166-1 country code uniquely "
            "identifying this country (e.g. 'AT' "
            "for Austria, 'CH' for Switzerland)."
        ),
    )
    location = mapped_column(
        Geometry("POINT", srid=4326),
        nullable=False,
        comment=(
            "Geographic centroid of the country as a "
            "PostGIS Point in WGS 84 (SRID 4326), "
            "used for map placement and proximity "
            "searches."
        ),
    )
    name_common: Mapped[str | None] = mapped_column(
        Text,
        comment=(
            "Common (colloquial) English name of the "
            "country, which may differ from the "
            "canonical name."
        ),
    )
    name_common_de: Mapped[str | None] = mapped_column(
        Text,
        comment=("German (de) translation of the common country name."),
    )
    name_common_pl: Mapped[str | None] = mapped_column(
        Text,
        comment=("Polish (pl) translation of the common country name."),
    )
    name_official: Mapped[str | None] = mapped_column(
        Text,
        comment=(
            "Official English name of the country as "
            "used in formal or diplomatic contexts."
        ),
    )
    name_official_de: Mapped[str | None] = mapped_column(
        Text,
        comment=("German (de) translation of the official country name."),
    )
    name_official_pl: Mapped[str | None] = mapped_column(
        Text,
        comment=("Polish (pl) translation of the official country name."),
    )
    name_native_common = mapped_column(
        ARRAY(Text),
        nullable=True,
        comment=(
            "Array of common country names in native "
            "languages (e.g. ['Oesterreich'] for "
            "Austria)."
        ),
    )
    name_native_official = mapped_column(
        ARRAY(Text),
        nullable=True,
        comment=(
            "Array of official country names in "
            "native languages (e.g. ['Republik "
            "Oesterreich'] for Austria)."
        ),
    )
    languages = mapped_column(
        ARRAY(Text),
        nullable=True,
        comment=(
            "Array of official or widely spoken "
            "language codes for this country "
            "(e.g. ['de'] for Austria)."
        ),
    )
    currencies = mapped_column(
        ARRAY(Text),
        nullable=True,
        comment=(
            "Array of currency codes used in this "
            "country (e.g. ['EUR'] for Eurozone, "
            "['CHF'] for Switzerland)."
        ),
    )
    capital: Mapped[str | None] = mapped_column(
        Text,
        comment=("Capital city name in English (e.g. 'Vienna', 'Bern')."),
    )
    capital_de: Mapped[str | None] = mapped_column(
        Text,
        comment=(
            "German (de) translation of the capital city name (e.g. 'Wien')."
        ),
    )
    capital_pl: Mapped[str | None] = mapped_column(
        Text,
        comment=(
            "Polish (pl) translation of the capital city name (e.g. 'Wiedeń')."
        ),
    )
    icon_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("asset_agg_icon.id", ondelete="RESTRICT"),
        index=True,
        comment=(
            "FK to asset_agg_icon with RESTRICT delete. The flag of the "
            "country (an SVG). NULL until one is linked."
        ),
    )
