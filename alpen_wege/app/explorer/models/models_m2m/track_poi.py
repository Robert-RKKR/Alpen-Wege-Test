# Standard library
import uuid

# Third-party
from sqlalchemy import ForeignKey, Integer, UniqueConstraint, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import Base, CreatorMixin, TimestampMixin


class ExplorerM2mTrackPoi(TimestampMixin, CreatorMixin, Base):
    __tablename__ = "explorer_m2m_track_poi"
    __table_args__ = (
        UniqueConstraint(
            "track_id", "poi_id", name="uq_explorer_m2m_track_poi_track_poi"
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    slot_position: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        comment=(
            "Zero-based ordering position of this POI along the recorded "
            "track."
        ),
    )
    track_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("explorer_agg_track.id", ondelete="CASCADE"),
        nullable=False,
        comment=(
            "FK to explorer_agg_track with CASCADE delete. The recorded GPS "
            "activity during which this POI was visited."
        ),
    )
    poi_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("compendium_cat_poi.id", ondelete="CASCADE"),
        nullable=False,
        comment=(
            "FK to compendium_cat_poi with CASCADE delete. The Point of "
            "Interest visited during this track."
        ),
    )
    distance_m: Mapped[int | None] = mapped_column(
        Integer,
        comment="Along-track distance in meters from the track start to this POI.",
    )
