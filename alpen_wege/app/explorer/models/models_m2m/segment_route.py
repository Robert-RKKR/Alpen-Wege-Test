# Standard library
import uuid

# Third-party
from sqlalchemy import Boolean, ForeignKey, Index, Integer, UniqueConstraint, func, text
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import Base, CreatorMixin, TimestampMixin


class ExplorerM2mSegmentRoute(TimestampMixin, CreatorMixin, Base):
    __tablename__ = "explorer_m2m_segment_route"
    __table_args__ = (
        UniqueConstraint(
            "route_id", "slot_position", "segment_id",
            name="uq_segment_route_slot_segment",
        ),
        # at most one default per alternative group of a route (code checks
        # that there is exactly one)
        Index(
            "uq_segment_route_one_default", "route_id", "alt_group",
            unique=True, postgresql_where=text("is_default"),
        ),
        Index("ix_segment_route_segment_id", "segment_id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    segment_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("explorer_agg_segment.id", ondelete="RESTRICT"),
        nullable=False,
        comment=(
            "FK to explorer_agg_segment with RESTRICT delete: a segment that "
            "is used by a route cannot be deleted. The trail segment "
            "included in this route."
        ),
    )
    route_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("explorer_agg_route.id", ondelete="CASCADE"),
        nullable=False,
        comment=(
            "FK to explorer_agg_route with CASCADE delete. The parent route "
            "containing this segment."
        ),
    )
    slot_position: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        comment=(
            "Zero-based ordering position of this segment within the parent "
            "route. Determines the traversal sequence."
        ),
    )
    alt_group: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        comment=(
            "Alternative group identifier. Segments sharing the same "
            "alt_group and slot_position are alternative options for the same "
            "section of the route."
        ),
    )
    is_default: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        comment=(
            "Whether this segment is the default (preferred) choice within "
            "its alternative group."
        ),
    )
    is_reversed: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        comment=(
            "Whether this segment should be traversed in the reverse "
            "direction from its original recording."
        ),
    )
