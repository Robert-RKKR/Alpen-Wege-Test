# Standard library
import uuid

# Third-party
from sqlalchemy import ForeignKey, Integer, Real, Text, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import (
    Base,
    IdentificationL18nMixin,
    CreatorMixin,
    PublicMixin,
    TimestampMixin,
)


class ExplorerAggJourney(
    TimestampMixin, CreatorMixin, PublicMixin, IdentificationL18nMixin, Base
):
    __tablename__ = "explorer_agg_journey"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        description=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    name: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        description=(
            "Display name of the multi-day journey (e.g. 'Tour du Mont "
            "Blanc'). Required, overrides the mixin to enforce NOT NULL."
        ),
    )
    rating_avg: Mapped[float | None] = mapped_column(
        Real,
        description=(
            "Average user rating for this journey on a 1-5 scale, calculated "
            "from all submitted ratings."
        ),
    )
    rating_count: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        description=(
            "Total number of user ratings submitted"
            " for this journey. Defaults to 0."
        ),
    )
    length_days: Mapped[int | None] = mapped_column(
        Integer,
        description="Planned duration of the journey in days.",
    )
    agg_distance_m: Mapped[int | None] = mapped_column(
        Integer,
        description=(
            "Aggregate total horizontal distance across all routes in this "
            "journey, in meters."
        ),
    )
    agg_elevation_gain_m: Mapped[int | None] = mapped_column(
        Integer,
        description=(
            "Aggregate cumulative elevation gain across all routes in this "
            "journey, in meters."
        ),
    )
    agg_elevation_loss_m: Mapped[int | None] = mapped_column(
        Integer,
        description=(
            "Aggregate cumulative elevation loss across all routes in this "
            "journey, in meters."
        ),
    )
    agg_highest_point_m: Mapped[int | None] = mapped_column(
        Integer,
        description=(
            "Highest altitude above sea level in meters reached across all "
            "routes in this journey."
        ),
    )
    agg_lowest_point_m: Mapped[int | None] = mapped_column(
        Integer,
        description=(
            "Lowest altitude above sea level in meters across all routes in "
            "this journey."
        ),
    )
    agg_duration_s: Mapped[int | None] = mapped_column(
        Integer,
        description=(
            "Aggregate estimated total duration for the entire journey in "
            "seconds."
        ),
    )
    difficulty_level_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("core_ref_difficulty_level.id"),
        description=(
            "FK to core_ref_difficulty_level. General difficulty "
            "classification for this journey."
        ),
    )
    difficulty_sport_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("core_ref_difficulty_sport.id"),
        description=(
            "FK to core_ref_difficulty_sport. Sport-specific difficulty "
            "grading for this journey."
        ),
    )
    sport_type_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("core_ref_sport_type.id"),
        description=(
            "FK to core_ref_sport_type. The primary sport activity for this "
            "journey (e.g. hiking, trekking)."
        ),
    )
    condition_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("explorer_sub_plan_conditions.id"),
        description=(
            "FK to explorer_sub_plan_conditions. Links to planning "
            "requirements (equipment, permits, best months) for this journey."
        ),
    )
