# Standard library
import uuid

# Third-party
from sqlalchemy import ForeignKey, Integer, REAL, Text, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import (
    Base,
    IdentificationL18nMixin,
    CreatorMixin,
    PublicMixin,
    TimestampMixin,
)


class ExplorerAggSegment(
    TimestampMixin, CreatorMixin, PublicMixin, IdentificationL18nMixin, Base
):
    __tablename__ = "explorer_agg_segment"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    rating_avg: Mapped[float | None] = mapped_column(
        REAL,
        comment=(
            "Average user rating for this segment on a 1-5 scale, calculated "
            "from all submitted ratings."
        ),
    )
    rating_count: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        comment=(
            "Total number of user ratings submitted for this segment. "
            "Defaults to 0."
        ),
    )
    sport_type_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_sport_type.id"),
        nullable=False,
        comment=(
            "FK to core_ref_sport_type. The primary sport activity for this "
            "segment (e.g. hiking, trail running, ski touring)."
        ),
    )
    geo_record_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("explorer_sub_geo_record.id"),
        nullable=False,
        comment=(
            "FK to explorer_sub_geo_record. Links to the geographic data "
            "(GPX, elevation, distance) for this segment."
        ),
    )
    main_photo_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("asset_agg_photo.id"),
        comment=(
            "FK to asset_agg_photo. Primary photo of this segment shown in "
            "listings and detail views."
        ),
    )
    start_poi_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("compendium_cat_poi.id"),
        comment=(
            "FK to compendium_cat_poi. The Point of Interest where this "
            "segment begins."
        ),
    )
    end_poi_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("compendium_cat_poi.id"),
        comment=(
            "FK to compendium_cat_poi. The Point of Interest where this "
            "segment ends."
        ),
    )
    difficulty_level_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("core_ref_difficulty_level.id"),
        comment=(
            "FK to core_ref_difficulty_level. General difficulty "
            "classification for this segment (e.g. easy, moderate, "
            "difficult)."
        ),
    )
    difficulty_sport_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("core_ref_difficulty_sport.id"),
        comment=(
            "FK to core_ref_difficulty_sport. Sport-specific difficulty "
            "grading (e.g. T1-T6 for hiking, WS for ski touring)."
        ),
    )
