# Standard library
import uuid

# Third-party
from sqlalchemy import ForeignKey, Integer, Text, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import (
    Base,
    IdentificationL18nMixin,
    CreatorMixin,
    PublicMixin,
    TimestampMixin,
)


class ExplorerAggGear(
    TimestampMixin, CreatorMixin, PublicMixin, IdentificationL18nMixin, Base
):
    __tablename__ = "explorer_agg_gear"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    name: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        comment=(
            "Display name of the gear item (e.g. ). Required, overrides the "
            "mixin to enforce NOT NULL."
        ),
    )
    company_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_company.id"),
        nullable=False,
        comment=(
            "FK to core_ref_company. The manufacturer or brand of this gear "
            "item (e.g. Salomon, Arc"
        ),
    )
    model: Mapped[str | None] = mapped_column(
        Text,
        comment=(
            "Specific model name or number within the brand's product line."
        ),
    )
    weight_g: Mapped[int | None] = mapped_column(
        Integer,
        comment=(
            "Weight of the gear item in grams, used for pack weight "
            "calculations."
        ),
    )
    gear_type_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_gear_type.id"),
        nullable=False,
        comment=(
            "FK to core_ref_gear_type. Categorizes the gear (e.g. footwear, "
            "jacket, backpack, poles)."
        ),
    )
    main_photo_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("asset_agg_photo.id"),
        comment=(
            "FK to asset_agg_photo. Primary photo of this gear item shown in "
            "listings and detail views."
        ),
    )
