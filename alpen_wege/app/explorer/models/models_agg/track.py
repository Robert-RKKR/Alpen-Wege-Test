# Standard library
import uuid
from datetime import datetime

# Third-party
from sqlalchemy import DateTime, ForeignKey, Text, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import (
    Base,
    IdentificationL18nMixin,
    CreatorMixin,
    PublicMixin,
    TimestampMixin,
)


class ExplorerAggTrack(
    TimestampMixin, CreatorMixin, PublicMixin, IdentificationL18nMixin, Base
):
    __tablename__ = "explorer_agg_track"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        description=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    name: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        description=(
            "Display name of the recorded GPS activity (e.g. 'Morning hike to "
            "Kreuzeck'). Required, overrides the mixin to enforce NOT NULL."
        ),
    )
    recorded_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        description=(
            "Timezone-aware UTC timestamp of when the GPS activity was "
            "actually recorded in the field."
        ),
    )
    sport_type_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("core_ref_sport_type.id"),
        description=(
            "FK to core_ref_sport_type. The sport"
            " activity type for this track (e.g."
            " hiking, trail running, ski touring)."
        ),
    )
    difficulty_level_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("core_ref_difficulty_level.id"),
        description=(
            "FK to core_ref_difficulty_level. General difficulty "
            "classification assigned to this track after recording."
        ),
    )
    difficulty_sport_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("core_ref_difficulty_sport.id"),
        description=(
            "FK to core_ref_difficulty_sport. Sport-specific difficulty "
            "grading for this track."
        ),
    )
    main_photo_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("asset_agg_photo.id"),
        description=(
            "FK to asset_agg_photo. Primary photo of this track shown in "
            "listings and detail views."
        ),
    )
    geo_record_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("explorer_sub_geo_record.id"),
        description=(
            "FK to explorer_sub_geo_record. Links to"
            " the geographic data (GPX, elevation,"
            " distance) recorded for this track."
        ),
    )
    condition_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("explorer_sub_conditions.id"),
        description=(
            "FK to explorer_sub_conditions. Links to the weather and trail "
            "conditions observed during this track."
        ),
    )
    start_poi_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("compendium_cat_poi.id"),
        description=(
            "FK to compendium_cat_poi. The Point of Interest where this track "
            "started."
        ),
    )
    end_poi_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("compendium_cat_poi.id"),
        description=(
            "FK to compendium_cat_poi. The Point of Interest where this track "
            "ended."
        ),
    )
