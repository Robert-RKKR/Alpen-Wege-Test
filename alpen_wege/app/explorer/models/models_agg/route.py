# Standard library
import uuid

# Third-party
from sqlalchemy import ForeignKey, Integer, Real, Text, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import (
    Base,
    IdentificationL18nMixin,
    CreatorMixin,
    PublicMixin,
    TimestampMixin,
)


class ExplorerAggRoute(
    TimestampMixin, CreatorMixin, PublicMixin, IdentificationL18nMixin, Base
):
    __tablename__ = "explorer_agg_route"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        description=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    name: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        description=(
            "Display name of the planned route (e.g. ). Required, overrides "
            "the mixin to enforce NOT NULL."
        ),
    )
    rating_avg: Mapped[float | None] = mapped_column(
        Real,
        description=(
            "Average user rating for this route on a 1-5 scale, calculated "
            "from all submitted ratings."
        ),
    )
    rating_count: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        description=(
            "Total number of user ratings submitted for this route. Defaults "
            "to 0."
        ),
    )
    agg_distance_m: Mapped[int | None] = mapped_column(
        Integer,
        description=(
            "Aggregate total horizontal distance of all segments in this "
            "route, in meters."
        ),
    )
    agg_elevation_gain_m: Mapped[int | None] = mapped_column(
        Integer,
        description=(
            "Aggregate cumulative elevation gain across all segments in this "
            "route, in meters."
        ),
    )
    agg_elevation_loss_m: Mapped[int | None] = mapped_column(
        Integer,
        description=(
            "Aggregate cumulative elevation loss across all segments in this "
            "route, in meters."
        ),
    )
    agg_highest_point_m: Mapped[int | None] = mapped_column(
        Integer,
        description=(
            "Highest altitude above sea level in meters reached across all "
            "segments in this route."
        ),
    )
    agg_lowest_point_m: Mapped[int | None] = mapped_column(
        Integer,
        description=(
            "Lowest altitude above sea level in meters across all segments in "
            "this route."
        ),
    )
    agg_duration_s: Mapped[int | None] = mapped_column(
        Integer,
        description=(
            "Aggregate estimated total duration for the entire route in "
            "seconds."
        ),
    )
    plan_condition_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("explorer_sub_plan_conditions.id"),
        description=(
            "FK to explorer_sub_plan_conditions. Links to planning "
            "requirements (equipment, permits, best months) for this route."
        ),
    )
    sport_type_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_sport_type.id"),
        nullable=False,
        description=(
            "FK to core_ref_sport_type. The primary sport activity for this "
            "route (e.g. hiking, trail running)."
        ),
    )
    difficulty_level_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_difficulty_level.id"),
        nullable=False,
        description=(
            "FK to core_ref_difficulty_level. General difficulty "
            "classification for this route. Required."
        ),
    )
    difficulty_sport_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("core_ref_difficulty_sport.id"),
        nullable=False,
        description=(
            "FK to core_ref_difficulty_sport. Sport-specific difficulty "
            "grading for this route. Required."
        ),
    )
