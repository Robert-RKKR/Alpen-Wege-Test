# Standard library
import uuid
from datetime import date

# Third-party
from sqlalchemy import Date, ForeignKey, Integer, Text, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import (
    Base,
    IdentificationL18nMixin,
    CreatorMixin,
    PublicMixin,
    TimestampMixin,
)


class ExplorerAggTrip(
    TimestampMixin, CreatorMixin, PublicMixin, IdentificationL18nMixin, Base
):
    __tablename__ = "explorer_agg_trip"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        description=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    name: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        description=(
            "Display name of the trip (e.g. ). Required, overrides the mixin "
            "to enforce NOT NULL."
        ),
    )
    length_days: Mapped[int | None] = mapped_column(
        Integer,
        description="Total number of days the trip spans.",
    )
    first_day: Mapped[date | None] = mapped_column(
        Date,
        description="Calendar date of the first day of the trip.",
    )
    last_day: Mapped[date | None] = mapped_column(
        Date,
        description="Calendar date of the last day of the trip.",
    )
    sport_type_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("core_ref_sport_type.id"),
        description=(
            "FK to core_ref_sport_type. The primary sport activity for this "
            "trip (e.g. hiking, mountaineering)."
        ),
    )
