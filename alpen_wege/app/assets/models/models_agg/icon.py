# Standard library
import uuid

# Third-party
from sqlalchemy import CHAR, CheckConstraint, DDL, Text, UniqueConstraint, event, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import (
    Base,
    CreatorMixin,
    NameL18nMixin,
    SummaryL18nMixin,
    TimestampMixin,
)


class AssetAggIcon(
    TimestampMixin,
    CreatorMixin,
    NameL18nMixin,
    SummaryL18nMixin,
    Base,
):
    __tablename__ = "asset_agg_icon"
    __table_args__ = (
        UniqueConstraint("key", name="uq_asset_agg_icon_key"),
        CheckConstraint(r"key ~ '^[a-z0-9_.-]{1,100}$'", name="ck_asset_agg_icon_key"),
        CheckConstraint(r"svg ~ '^<svg[\s>]' AND octet_length(svg) <= 1048576", name="ck_asset_agg_icon_svg"),
        CheckConstraint(r"sha256 ~ '^[0-9a-f]{64}$'", name="ck_asset_agg_icon_sha256"),
        {"comment": (
            "Pictures that stand for something (a flag, a sport symbol): an SVG stored as text. Linked from reference "
            "tables, countries and regions through icon_id."
        )},
    )

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    name: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        comment=(
            "Display name of the icon in the default language (English). "
            "Required field that overrides the nullable mixin default."
        ),
    )
    key: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        comment=(
            "Unique machine-readable name, lower-case letters, digits and "
            "_ . - only (for example flag_at, flag_ch_zh, sport_hiking). A "
            "seeded icon's id is computed from it, and icons_link.sql uses it "
            "to give countries and regions their flag."
        ),
    )
    svg: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        deferred=True,
        comment=(
            "The picture as SVG text. Always the cleaned copy written by the "
            "application (no script, no external links); never store an "
            "uploaded file as it came. Deferred: it is only read when the "
            "file itself is served."
        ),
    )
    sha256: Mapped[str] = mapped_column(
        CHAR(64),
        nullable=False,
        comment=(
            "SHA-256 (hex) of the stored svg text. Used as ETag and to find "
            "duplicates."
        ),
    )


# Keeps updated_at current on every UPDATE. Only runs when create_all creates the table;
# scripts/sql/icons_ddl.sql creates the same trigger.
event.listen(
    AssetAggIcon.__table__,
    "after_create",
    DDL(
        "CREATE TRIGGER trg_set_updated_at BEFORE UPDATE ON asset_agg_icon "
        "FOR EACH ROW EXECUTE FUNCTION moddatetime('updated_at')"
    ),
)
