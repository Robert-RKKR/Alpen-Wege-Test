# Standard library
import uuid

# Third-party
from sqlalchemy import Text, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import (
    Base,
    NameL18nMixin,
    CreatorMixin,
    PublicMixin,
    SummaryL18nMixin,
    TimestampMixin,
)


class AssetAggGpx(
    TimestampMixin,
    CreatorMixin,
    PublicMixin,
    NameL18nMixin,
    SummaryL18nMixin,
    Base,
):
    __tablename__ = "asset_agg_gpx"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    name: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        comment=(
            "Display name of the GPX track in the default language (English). "
            "Required field that overrides the nullable mixin default to "
            "ensure every GPX asset has a name."
        ),
    )
    path: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        unique=True,
        comment=(
            "Unique file system or object storage path to the GPX file. Used "
            "to locate and serve the file."
        ),
    )
