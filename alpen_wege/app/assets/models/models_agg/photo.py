# Standard library
import uuid
from datetime import datetime

# Third-party
from geoalchemy2 import Geometry
from sqlalchemy import DateTime, Integer, Text, func
from sqlalchemy.orm import Mapped, mapped_column

# Local application
from app.core.base import (
    Base,
    NameL18nMixin,
    CreatorMixin,
    PublicMixin,
    SummaryL18nMixin,
    TimestampMixin,
)


class AssetAggPhoto(
    TimestampMixin,
    CreatorMixin,
    PublicMixin,
    NameL18nMixin,
    SummaryL18nMixin,
    Base,
):
    __tablename__ = "asset_agg_photo"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        comment=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    name: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        comment=(
            "Display name of the photo in the default language (English). "
            "Required field that overrides the nullable mixin default to "
            "ensure every photo asset has a name."
        ),
    )
    location = mapped_column(
        Geometry("POINT", srid=4326),
        nullable=True,
        comment=(
            "Geographic coordinates (WGS 84, SRID 4326) indicating where the "
            "photo was taken. Stored as a PostGIS Point geometry for spatial "
            "queries and map display."
        ),
    )
    altitude_m: Mapped[int | None] = mapped_column(
        Integer,
        comment=(
            "Altitude in metres above sea level at which the photo was taken, "
            "typically extracted from EXIF GPS data. Nullable when altitude "
            "information is unavailable."
        ),
    )
    taken_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        comment=(
            "Timezone-aware timestamp of when the photo was originally "
            "captured, typically extracted from EXIF metadata. Nullable when "
            "capture time is unknown."
        ),
    )
    path: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        unique=True,
        comment=(
            "Unique file system or object storage path to the photo file. "
            "Used to locate and serve the image."
        ),
    )
