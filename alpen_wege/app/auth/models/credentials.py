# Standard library
import uuid
from datetime import datetime

# Third-party
from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Text,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

# Local application
from app.core.base import Base, TimestampMixin


class AuthUserCredentials(TimestampMixin, Base):
    __tablename__ = "auth_user_credentials"
    __table_args__ = (
        CheckConstraint(
            "user_group IN ('admin', 'editor', 'user')",
            name="ck_auth_user_credentials_user_group",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        server_default=func.gen_random_uuid(),
        description=(
            "Primary key UUID, auto-generated by the database using "
            "gen_random_uuid()."
        ),
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("profile_usr_user.id", ondelete="CASCADE"),
        unique=True,
        nullable=False,
        description=(
            "One-to-one FK reference to profile_usr_user.id. Each user has "
            "exactly one credentials row. Cascades on user deletion."
        ),
    )
    password_hash: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        description=(
            "Bcrypt-hashed password string. Never stored or transmitted in "
            "plaintext. Used by the login flow to verify user-supplied "
            "passwords."
        ),
    )
    user_group: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        server_default="user",
        description=(
            "Authorization group determining"
            " the user's permission level."
            " Must be one of 'admin', 'editor',"
            " or 'user'. Defaults to 'user'."
        ),
    )
    is_verified: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        server_default="false",
        description=(
            "Whether the user has verified their email address. Defaults to "
            "false on registration. Set to true after successful email "
            "verification flow."
        ),
    )
    last_login_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        description="Timezone-aware UTC timestamp of the user",
    )

    user = relationship("ProfileUsrUser", back_populates="credentials")
