-- Icons, STEP 1: new table asset_agg_icon (svg text instead of a file) and a NULLABLE link icon_id on 22 tables:
-- the 20 reference tables that have an icon text (19 core_ref_* + core_ref_resource_type), compendium_cat_country
-- and compendium_cat_region. The old text column icon is NOT touched. Idempotent, one transaction.
-- A fresh create_all database already has all of this (the models are changed in the same delivery).
--   sudo docker exec -i alpen-postgres psql -U alpenwege -d alpenwege < scripts/sql/icons_ddl.sql
-- Order: icons_preflight.sql -> THIS SCRIPT -> new application code -> init_seed.py -> seed_icons.py -> icons_link.sql
\set ON_ERROR_STOP on
BEGIN;

CREATE EXTENSION IF NOT EXISTS moddatetime;

-- 1. the table -----------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS asset_agg_icon (
    id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    created_by  uuid        NOT NULL REFERENCES profile_usr_user (id),
    name        text        NOT NULL,
    name_de     text,
    name_pl     text,
    summary     text,
    summary_de  text,
    summary_pl  text,
    key         text        NOT NULL,
    svg         text        NOT NULL,
    sha256      char(64)    NOT NULL,
    CONSTRAINT uq_asset_agg_icon_key UNIQUE (key),
    CONSTRAINT ck_asset_agg_icon_key CHECK (key ~ '^[a-z0-9_.-]{1,100}$'),
    CONSTRAINT ck_asset_agg_icon_svg CHECK (svg ~ '^<svg[\s>]' AND octet_length(svg) <= 1048576),
    CONSTRAINT ck_asset_agg_icon_sha256 CHECK (sha256 ~ '^[0-9a-f]{64}$')
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'trg_set_updated_at' AND tgrelid = 'asset_agg_icon'::regclass) THEN
        CREATE TRIGGER trg_set_updated_at BEFORE UPDATE ON asset_agg_icon
            FOR EACH ROW EXECUTE FUNCTION moddatetime('updated_at');
    END IF;
END $$;

COMMENT ON TABLE  asset_agg_icon IS 'Pictures that stand for something (a flag, a sport symbol): an SVG stored as text. Linked from reference tables, countries and regions through icon_id.';
COMMENT ON COLUMN asset_agg_icon.id IS 'Primary key UUID, auto-generated by the database using gen_random_uuid().';
COMMENT ON COLUMN asset_agg_icon.created_at IS 'Timezone-aware UTC timestamp of when the row was first created, set automatically by the database on INSERT.';
COMMENT ON COLUMN asset_agg_icon.updated_at IS 'Timezone-aware UTC timestamp of the last modification, initially set to created_at and kept current by the moddatetime trigger on every UPDATE.';
COMMENT ON COLUMN asset_agg_icon.created_by IS 'UUID of the user who originally created this record. References profile_usr_user.id and is required (NOT NULL).';
COMMENT ON COLUMN asset_agg_icon.name IS 'Display name of the icon in the default language (English). Required field that overrides the nullable mixin default.';
COMMENT ON COLUMN asset_agg_icon.name_de IS 'German (de) translation of the display name.';
COMMENT ON COLUMN asset_agg_icon.name_pl IS 'Polish (pl) translation of the display name.';
COMMENT ON COLUMN asset_agg_icon.summary IS 'Short summary text in the default language (English), used for previews and list views.';
COMMENT ON COLUMN asset_agg_icon.summary_de IS 'German (de) translation of the short summary.';
COMMENT ON COLUMN asset_agg_icon.summary_pl IS 'Polish (pl) translation of the short summary.';
COMMENT ON COLUMN asset_agg_icon.key IS 'Unique machine-readable name, lower-case letters, digits and _ . - only (for example flag_at, flag_ch_zh, sport_hiking). The same text that the reference tables hold in their old icon column (compared in lower case); icons_link.sql uses it to set icon_id.';
COMMENT ON COLUMN asset_agg_icon.svg IS 'The picture as SVG text. Always the cleaned copy written by the application (no script, no external links); never store an uploaded file as it came. Deferred: it is only read when the file itself is served.';
COMMENT ON COLUMN asset_agg_icon.sha256 IS 'SHA-256 (hex) of the stored svg text. Used as ETag and to find duplicates.';

-- 2. the nullable link on the 22 tables -------------------------------------------------------------------
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'core_ref_resource_type', 'core_ref_achievement_category', 'core_ref_achievement_scope', 'core_ref_achievement_type',
        'core_ref_company', 'core_ref_compendium_type', 'core_ref_difficulty_level', 'core_ref_difficulty_sport',
        'core_ref_gear_type', 'core_ref_point_reason', 'core_ref_post_type', 'core_ref_rarity', 'core_ref_region_type',
        'core_ref_schedule_status', 'core_ref_snow_condition', 'core_ref_sport_type', 'core_ref_trail_condition',
        'core_ref_visibility', 'core_ref_waypoint_type', 'core_ref_weather_condition',
        'compendium_cat_country', 'compendium_cat_region']
    LOOP
        EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS icon_id uuid REFERENCES asset_agg_icon (id) ON DELETE RESTRICT', t);
        EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I (icon_id)', 'ix_' || t || '_icon_id', t);
        EXECUTE format('COMMENT ON COLUMN %I.icon_id IS %L', t, CASE t
            WHEN 'compendium_cat_country' THEN 'FK to asset_agg_icon with RESTRICT delete. The flag of the country (an SVG). NULL until one is linked.'
            WHEN 'compendium_cat_region'  THEN 'FK to asset_agg_icon with RESTRICT delete. The flag or coat of arms of the region (an SVG). NULL until one is linked.'
            ELSE 'FK to asset_agg_icon with RESTRICT delete. The picture of this reference value (an SVG). NULL until one is linked; the text column icon is still used until then.' END);
    END LOOP;
END $$;

COMMIT;
