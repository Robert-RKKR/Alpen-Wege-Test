-- Collectible card: order number, difficulty, render bookkeeping. Idempotent, one transaction.
--   sudo docker exec -i alpen-postgres psql -U alpenwege -d alpenwege < scripts/sql/card_render_ddl.sql
\set ON_ERROR_STOP on
BEGIN;

-- 1. card_number: unique order number printed as "No 013" -------------------------------------------
-- Existing rows get numbers in creation order. BY DEFAULT (not ALWAYS) so cards printed earlier can keep
-- their old number; after setting numbers by hand, move the sequence past the largest one:
--   SELECT setval(pg_get_serial_sequence('compendium_cat_card', 'card_number'), max(card_number)) FROM compendium_cat_card;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_name = 'compendium_cat_card' AND column_name = 'card_number') THEN
        ALTER TABLE compendium_cat_card ADD COLUMN card_number integer;
        UPDATE compendium_cat_card c SET card_number = n.rn
          FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) AS rn FROM compendium_cat_card) n
         WHERE c.id = n.id;
        ALTER TABLE compendium_cat_card ALTER COLUMN card_number SET NOT NULL;
        ALTER TABLE compendium_cat_card ALTER COLUMN card_number ADD GENERATED BY DEFAULT AS IDENTITY;
        PERFORM setval(pg_get_serial_sequence('compendium_cat_card', 'card_number'),
                       coalesce((SELECT max(card_number) FROM compendium_cat_card), 0) + 1, false);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_compendium_cat_card_number') THEN
        ALTER TABLE compendium_cat_card ADD CONSTRAINT uq_compendium_cat_card_number UNIQUE (card_number);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_compendium_cat_card_number_positive') THEN
        ALTER TABLE compendium_cat_card ADD CONSTRAINT ck_compendium_cat_card_number_positive CHECK (card_number > 0);
    END IF;
END $$;

COMMENT ON COLUMN compendium_cat_card.card_number IS 'Unique order number of the card, printed on it as No 013. Assigned from an identity sequence; may be set explicitly (create, update, CSV) to keep the number of a card printed earlier.';

-- 2. difficulty: same pair of references as segment and route -----------------------------------------
ALTER TABLE compendium_cat_card ADD COLUMN IF NOT EXISTS difficulty_level_id uuid;
ALTER TABLE compendium_cat_card ADD COLUMN IF NOT EXISTS difficulty_sport_id uuid;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'compendium_cat_card_difficulty_level_id_fkey') THEN
        ALTER TABLE compendium_cat_card ADD CONSTRAINT compendium_cat_card_difficulty_level_id_fkey
            FOREIGN KEY (difficulty_level_id) REFERENCES core_ref_difficulty_level (id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'compendium_cat_card_difficulty_sport_id_fkey') THEN
        ALTER TABLE compendium_cat_card ADD CONSTRAINT compendium_cat_card_difficulty_sport_id_fkey
            FOREIGN KEY (difficulty_sport_id) REFERENCES core_ref_difficulty_sport (id);
    END IF;
END $$;

COMMENT ON COLUMN compendium_cat_card.difficulty_level_id IS 'FK to core_ref_difficulty_level. Optional general difficulty of reaching this place. NULL (and no difficulty_sport_id) hides the difficulty on the card.';
COMMENT ON COLUMN compendium_cat_card.difficulty_sport_id IS 'FK to core_ref_difficulty_sport. Optional sport-specific grade (e.g. SAC T3). Shown on the card instead of difficulty_level_id when both are set.';

-- 3. render bookkeeping: files under CARD_STORAGE_DIR/{id}/{lang}.{svg,png,jpg,pdf} -------------------
ALTER TABLE compendium_cat_card ADD COLUMN IF NOT EXISTS render_status varchar(16);
ALTER TABLE compendium_cat_card ADD COLUMN IF NOT EXISTS render_version smallint;
ALTER TABLE compendium_cat_card ADD COLUMN IF NOT EXISTS render_hash char(64);
ALTER TABLE compendium_cat_card ADD COLUMN IF NOT EXISTS rendered_at timestamptz;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_compendium_cat_card_render_status') THEN
        ALTER TABLE compendium_cat_card ADD CONSTRAINT ck_compendium_cat_card_render_status
            CHECK (render_status IN ('pending', 'rendering', 'done', 'failed'));
    END IF;
END $$;

COMMENT ON COLUMN compendium_cat_card.render_status IS 'State of the generated card files: pending, rendering, done or failed. NULL when never rendered.';
COMMENT ON COLUMN compendium_cat_card.render_version IS 'Template version the stored files were rendered with. A newer template version makes the files stale.';
COMMENT ON COLUMN compendium_cat_card.render_hash IS 'SHA-256 of the render models (all languages) the stored files were made from. Files are stale when it no longer matches.';
COMMENT ON COLUMN compendium_cat_card.rendered_at IS 'When the stored card files were rendered.';

COMMIT;
